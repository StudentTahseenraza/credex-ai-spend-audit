'use client';

import { Document, Page, Text, View, StyleSheet, Font } from '@react-pdf/renderer';
import { Button } from '../../components/ui/button';
import { FileDown } from 'lucide-react';
import { PDFDownloadLink } from '@react-pdf/renderer';

// Register font
Font.register({
  family: 'Inter',
  src: 'https://fonts.gstatic.com/s/inter/v12/UcC73FwrK3iLTeHuS_fvQtMwCp50KnMa1ZL7W0Q5nw.woff2',
});

const styles = StyleSheet.create({
  page: { padding: 40, backgroundColor: '#ffffff', fontFamily: 'Inter' },
  header: { fontSize: 24, fontWeight: 'bold', marginBottom: 20, color: '#2563eb' },
  subheader: { fontSize: 18, fontWeight: 'semibold', marginTop: 20, marginBottom: 10, color: '#1f2937' },
  text: { fontSize: 11, marginBottom: 8, color: '#4b5563', lineHeight: 1.5 },
  savingsBox: { backgroundColor: '#d1fae5', padding: 15, borderRadius: 8, marginVertical: 15, textAlign: 'center' },
  savingsNumber: { fontSize: 28, fontWeight: 'bold', color: '#065f46' },
  toolCard: { marginBottom: 12, padding: 12, borderWidth: 1, borderColor: '#e5e7eb', borderRadius: 8 },
  toolName: { fontSize: 14, fontWeight: 'bold', marginBottom: 4, color: '#1f2937' },
  divider: { borderBottomWidth: 1, borderBottomColor: '#e5e7eb', marginVertical: 15 },
  footer: { position: 'absolute', bottom: 30, left: 40, right: 40, fontSize: 9, textAlign: 'center', color: '#9ca3af' },
});

interface PDFExportProps {
  audit: {
    shareableId: string;
    totalMonthlySavings: number;
    totalAnnualSavings: number;
    tools: any[];
    aiSummary: string;
    teamSize: number;
    useCase: string;
  };
}

export function PDFExport({ audit }: PDFExportProps) {
  const PDFDocument = () => (
    <Document>
      <Page size="A4" style={styles.page}>
        <Text style={styles.header}>AI Spend Audit Report</Text>
        <Text style={[styles.text, { marginBottom: 20 }]}>Generated on {new Date().toLocaleDateString()}</Text>

        <View style={styles.savingsBox}>
          <Text style={styles.savingsNumber}>
            {audit.totalMonthlySavings > 0 ? `Save $${audit.totalMonthlySavings}/month` : 'Already Optimized'}
          </Text>
          <Text style={[styles.text, { marginTop: 5, color: '#065f46' }]}>
            ${audit.totalAnnualSavings}/year in potential savings
          </Text>
        </View>

        <Text style={styles.subheader}>Team Overview</Text>
        <Text style={styles.text}>Team Size: {audit.teamSize} people</Text>
        <Text style={styles.text}>Primary Use Case: {audit.useCase}</Text>

        <Text style={styles.subheader}>Per-Tool Analysis</Text>
        {audit.tools.map((tool, idx) => (
          <View key={idx} style={styles.toolCard}>
            <Text style={styles.toolName}>{tool.name.toUpperCase()}</Text>
            <Text style={styles.text}>Current Plan: {tool.plan}</Text>
            <Text style={styles.text}>Monthly Spend: ${tool.monthlySpend}</Text>
            {tool.recommendation.monthlySavings > 0 && (
              <>
                <Text style={styles.text}>Recommendation: {tool.recommendation.action} to {tool.recommendation.suggestedPlan || tool.recommendation.suggestedTool}</Text>
                <Text style={[styles.text, { color: '#10b981', fontWeight: 'bold' }]}>Save: ${tool.recommendation.monthlySavings}/month</Text>
              </>
            )}
            <Text style={[styles.text, { fontSize: 10, marginTop: 5 }]}>{tool.recommendation.reason}</Text>
          </View>
        ))}

        <Text style={styles.subheader}>AI Summary</Text>
        <Text style={styles.text}>{audit.aiSummary}</Text>

        <View style={styles.divider} />

        <Text style={styles.text}>
          {audit.totalMonthlySavings > 500 
            ? "🎉 High savings detected! Credex can help you capture additional 20% savings through discounted AI credits."
            : "Share this report with your team to implement these savings."}
        </Text>

        <Text style={styles.footer}>Generated by Credex AI Spend Audit • credex.rocks</Text>
      </Page>
    </Document>
  );

  return (
    <PDFDownloadLink document={<PDFDocument />} fileName={`ai-spend-audit-${audit.shareableId}.pdf`}>
      {({ loading }) => (
        <Button variant="outline" className="flex-1">
          <FileDown className="h-4 w-4 mr-2" />
          {loading ? 'Generating PDF...' : 'Export PDF'}
        </Button>
      )}
    </PDFDownloadLink>
  );
}